// Rasterizes the dot-matrix display's fonts into js/dmd-glyphs.js.
// Small text: Silkscreen at 8px, one glyph per character, composed at runtime.
// Large words: Archivo, ultra-condensed 800 at 17px, baked whole so kerning survives.
//
// Usage: serve the repository root (python3 -m http.server 8765), then
//   node tools/bake-dmd-glyphs.mjs http://127.0.0.1:8765
import { writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';

// CommonJS resolution so a globally installed Playwright is found too.
const { chromium } = createRequire(import.meta.url)('playwright');

const base = process.argv[2] || 'http://127.0.0.1:8765';
const SMALL = " ABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789.,:;-!?'&/()+#";
const BIG = ['DYLAN HUGHES', 'WEBSITES', 'GAME SOFTWARE', 'PRINTED PARTS', 'TILT', '404'];

const browser = await chromium.launch();
const page = await browser.newPage();
await page.goto(base + '/fonts/');
const data = await page.evaluate(async ({ SMALL, BIG, base }) => {
  const faces = [
    new FontFace('DMDSmall', `url(${base}/fonts/silkscreen-400.woff2)`),
    new FontFace('DMDBig', `url(${base}/fonts/archivo.woff2)`, { weight: '100 900', stretch: '62% 125%' }),
  ];
  for (const f of faces) document.fonts.add(await f.load());

  const canvas = document.createElement('canvas');
  canvas.width = 240; canvas.height = 32;
  const ctx = canvas.getContext('2d', { willReadFrequently: true });
  const hex = bits => bits.match(/.{1,4}/g).map(n => parseInt(n.padEnd(4, '0'), 2).toString(16)).join('');

  function grab(draw, threshold) {
    ctx.clearRect(0, 0, 240, 32);
    draw();
    const px = ctx.getImageData(0, 0, 240, 32).data;
    const rows = [];
    for (let y = 0; y < 32; y++) {
      let r = '';
      for (let x = 0; x < 240; x++) r += px[(y * 240 + x) * 4 + 3] > threshold ? '1' : '0';
      rows.push(r);
    }
    return rows;
  }

  const small = {};
  ctx.font = '8px DMDSmall';
  ctx.textBaseline = 'top';
  for (const ch of SMALL) {
    const rows = grab(() => { ctx.font = '8px DMDSmall'; ctx.textBaseline = 'top'; ctx.fillText(ch, 0, 0); }, 127).slice(0, 7);
    const advance = Math.round(ctx.measureText(ch).width);
    small[ch] = { w: advance, rows: rows.map(r => hex(r.slice(0, advance || 1))) };
  }

  const big = {};
  for (const word of BIG) {
    const rows = grab(() => {
      ctx.font = '800 17px DMDBig';
      ctx.fontStretch = 'ultra-condensed';
      ctx.textBaseline = 'alphabetic';
      ctx.fillText(word, 1, 20);
    }, 110);
    const lit = rows.map((r, y) => [r, y]).filter(([r]) => r.includes('1'));
    const top = lit[0][1], bottom = lit[lit.length - 1][1];
    let left = 240, right = 0;
    for (const [r] of lit) { left = Math.min(left, r.indexOf('1')); right = Math.max(right, r.lastIndexOf('1')); }
    const w = right - left + 1;
    big[word] = { w, rows: rows.slice(top, bottom + 1).map(r => hex(r.slice(left, right + 1))) };
  }
  return { small, big };
}, { SMALL, BIG, base });
await browser.close();

writeFileSync(new URL('../js/dmd-glyphs.js', import.meta.url),
  '/* Generated by tools/bake-dmd-glyphs.mjs. Rows are hex bitmaps, left to right. */\n' +
  'window.DMD_GLYPHS = ' + JSON.stringify(data) + ';\n');
console.log('small glyphs:', Object.keys(data.small).length, 'big words:', Object.entries(data.big).map(([k, v]) => `${k} ${v.w}x${v.rows.length}`).join(', '));
